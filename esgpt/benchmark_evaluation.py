def read_jsonl(path: Path) -> List[Dict[str, Any]]:
    rows: List[Dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def write_jsonl(path: Path, rows: Sequence[Dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False, default=str) + "\n")


def write_json(path: Path, payload: Dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        json.dump(payload, handle, ensure_ascii=False, indent=2, default=str)


def write_csv(path: Path, rows: Sequence[Dict[str, Any]], fieldnames: Sequence[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow({field: row.get(field, "") for field in fieldnames})


def safe_float_mean(values: Sequence[Any]) -> Optional[float]:
    numeric = [float(value) for value in values if isinstance(value, (int, float)) and not math.isnan(float(value))]
    if not numeric:
        return None
    return sum(numeric) / len(numeric)


def average_metric(rows: Sequence[Dict[str, Any]], metric_name: str) -> float | None:
    return safe_float_mean([row.get(metric_name) for row in rows])


def extract_assistant_answer_text(record: Dict[str, Any]) -> str:
    messages = record.get("messages")
    if isinstance(messages, list) and messages:
        for message in reversed(messages):
            if isinstance(message, dict) and message.get("role") == "assistant":
                content = str(message.get("content", ""))
                parsed, _ = safe_json_loads(content)
                if isinstance(parsed, dict) and "answer" in parsed:
                    return str(parsed.get("answer", ""))
                return content
    for key in ("answer", "gold", "gold_answer", "correct_answer", "output", "label"):
        if record.get(key) not in (None, ""):
            return str(record[key])
    return ""


def extract_prediction_answer_text(raw_prediction: str) -> str:
    parsed, _ = safe_json_loads(raw_prediction)
    if isinstance(parsed, dict):
        for key in ("answer", "label", "response", "output", "prediction"):
            if parsed.get(key) not in (None, ""):
                return str(parsed[key])
    return str(raw_prediction or "").strip()


def parse_prediction_label(raw_prediction: str) -> str:
    parsed, _ = safe_json_loads(raw_prediction)
    if isinstance(parsed, dict):
        for key in LABEL_CANDIDATES:
            value = parsed.get(key)
            if value not in (None, ""):
                return canonical_text(value)
        scalar_values = [value for value in parsed.values() if isinstance(value, (str, int, float, bool))]
        if len(scalar_values) == 1:
            return canonical_text(scalar_values[0])
    text = str(raw_prediction or "").strip()
    return canonical_text(text)


def normalize_classification_label(label: Any, *, task_name: str = "") -> str:
    return canonical_text(label)


def classification_gold_label(record: Dict[str, Any]) -> str:
    task_name = str(record.get("task_name") or record.get("source_folder") or "")
    detected_label = record.get("detected_label")
    if detected_label not in (None, "", "__unknown_label__"):
        return normalize_classification_label(detected_label, task_name=task_name)
    return normalize_classification_label(
        parse_prediction_label(extract_assistant_answer_text(record)),
        task_name=task_name,
    )


def record_task_key(record: Dict[str, Any]) -> str:
    return str(record.get("task_name") or record.get("source_folder") or "")


def extract_valid_label_from_text(raw_prediction: str, valid_labels: set[str]) -> Optional[str]:
    text = canonical_text(raw_prediction)
    if not text or not valid_labels or len(text) > MAX_LABEL_EXTRACTION_TEXT_CHARS:
        return None
    if text in valid_labels:
        return text

    matches: List[Tuple[int, int, str]] = []
    for label in sorted(valid_labels, key=len, reverse=True):
        pattern = rf"(?<![a-z0-9]){re.escape(label)}(?![a-z0-9])"
        for match in re.finditer(pattern, text):
            matches.append((match.start(), match.end(), label))
    if not matches:
        return None

    filtered = []
    for start, end, label in matches:
        contained_in_longer = any(
            other_start <= start
            and end <= other_end
            and len(other_label) > len(label)
            for other_start, other_end, other_label in matches
        )
        if not contained_in_longer:
            filtered.append((start, end, label))
    unique_labels = {label for _, _, label in filtered}
    if len(unique_labels) == 1:
        return next(iter(unique_labels))
    return None


def classification_prediction_label(
    record: Dict[str, Any],
    prediction: Dict[str, Any],
    valid_labels: set[str],
) -> str:
    task_name = record_task_key(record)
    raw_prediction = prediction.get("raw_prediction", "")
    parsed_label = normalize_classification_label(parse_prediction_label(raw_prediction), task_name=task_name)
    if parsed_label in valid_labels:
        return parsed_label
    return INVALID_PREDICTION_LABEL


def classification_report_rows(golds: Sequence[str], preds: Sequence[str]) -> List[Dict[str, Any]]:
    labels = sorted(set(golds) | set(preds))
    rows: List[Dict[str, Any]] = []
    gold_counts = Counter(golds)
    for label in labels:
        tp = sum(1 for gold, pred in zip(golds, preds) if gold == label and pred == label)
        fp = sum(1 for gold, pred in zip(golds, preds) if gold != label and pred == label)
        fn = sum(1 for gold, pred in zip(golds, preds) if gold == label and pred != label)
        precision = tp / (tp + fp) if tp + fp else 0.0
        recall = tp / (tp + fn) if tp + fn else 0.0
        f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
        rows.append(
            {
                "label": label,
                "precision": precision,
                "recall": recall,
                "f1": f1,
                "support": gold_counts.get(label, 0),
            }
        )
    return rows


def confusion_matrix_rows(golds: Sequence[str], preds: Sequence[str]) -> List[Dict[str, Any]]:
    counter = Counter((gold, pred) for gold, pred in zip(golds, preds))
    return [
        {"gold_label": gold, "predicted_label": pred, "count": count}
        for (gold, pred), count in sorted(counter.items())
    ]


class ClassificationEvaluator(BaseEvaluator):
    evaluator_name = "ClassificationEvaluator"
    dataset_key = "classification"

    def evaluate(self, records: Sequence[Dict[str, Any]], predictions: Sequence[Dict[str, Any]]) -> Dict[str, Any]:
        golds = [classification_gold_label(record) for record in records]
        valid_labels_by_task: Dict[str, set[str]] = defaultdict(set)
        for record, gold in zip(records, golds):
            valid_labels_by_task[record_task_key(record)].add(gold)
        preds = [
            classification_prediction_label(record, prediction, valid_labels_by_task[record_task_key(record)])
            for record, prediction in zip(records, predictions)
        ]
        metrics = single_label_metrics(golds, preds)
        invalid_count = sum(pred == INVALID_PREDICTION_LABEL for pred in preds)
        metrics.update(
            {
                "example_count": len(records),
                "invalid_prediction_count": invalid_count,
                "invalid_prediction_rate": invalid_count / len(records) if records else 0.0,
                "classification_report": classification_report_rows(golds, preds),
                "confusion_matrix": confusion_matrix_rows(golds, preds),
            }
        )
        return metrics


def normalize_multilabel_item(value: Any) -> str:
    label = canonical_text(value)
    aliases = {
        "pay, ownership & control": "ownership & control",
        "pay": "ownership & control",
        "environmental": "related to environmental",
        "governance": "related to governance",
        "social": "related to social",
    }
    return aliases.get(label, label)


def labels_from_value(value: Any) -> List[str]:
    if value in (None, ""):
        return []
    if isinstance(value, list):
        return [normalize_multilabel_item(item) for item in value if normalize_multilabel_item(item)]
    if isinstance(value, tuple):
        return labels_from_value(list(value))
    if isinstance(value, str):
        parsed, _ = safe_json_loads(value)
        if isinstance(parsed, dict):
            return labels_from_value(parsed.get("categories") or parsed.get("labels") or parsed.get("category"))
        if isinstance(parsed, list):
            return labels_from_value(parsed)
        return [normalize_multilabel_item(value)] if normalize_multilabel_item(value) else []
    return [normalize_multilabel_item(value)] if normalize_multilabel_item(value) else []


def extract_multilabel_set_from_record(record: Dict[str, Any]) -> set[str]:
    for key in ("categories", "labels", "label"):
        labels = labels_from_value(record.get(key))
        if labels:
            return set(labels)
    return set(labels_from_value(extract_assistant_answer_text(record)))


def extract_multilabel_set_from_prediction(raw_prediction: str) -> set[str]:
    return set(labels_from_value(raw_prediction))


class MultiLabelClassificationEvaluator(BaseEvaluator):
    evaluator_name = "MultiLabelClassificationEvaluator"
    dataset_key = "classification"

    def evaluate(self, records: Sequence[Dict[str, Any]], predictions: Sequence[Dict[str, Any]]) -> Dict[str, Any]:
        gold_sets = [extract_multilabel_set_from_record(record) for record in records]
        pred_sets = [extract_multilabel_set_from_prediction(prediction.get("raw_prediction", "")) for prediction in predictions]
        tp = fp = fn = 0
        exact = 0
        jaccards = []
        for gold, pred in zip(gold_sets, pred_sets):
            tp += len(gold & pred)
            fp += len(pred - gold)
            fn += len(gold - pred)
            exact += int(gold == pred)
            union = gold | pred
            jaccards.append((len(gold & pred) / len(union)) if union else 1.0)
        precision, recall, f1 = precision_recall_f1(tp, fp, fn)
        total = len(records)
        return {
            "example_count": total,
            "micro_precision": precision,
            "micro_recall": recall,
            "micro_f1": f1,
            "sample_jaccard": safe_float_mean(jaccards) or 0.0,
            "exact_match": exact / total if total else 0.0,
            "avg_gold_labels": safe_float_mean([len(labels) for labels in gold_sets]) or 0.0,
            "avg_pred_labels": safe_float_mean([len(labels) for labels in pred_sets]) or 0.0,
        }


def numeric_value(text: Any) -> Optional[float]:
    matches = re.findall(r"[-+]?\d[\d,]*(?:\.\d+)?", str(text or ""))
    if not matches:
        return None
    try:
        return float(matches[0].replace(",", ""))
    except ValueError:
        return None


def compute_optional_bertscore_f1(predictions: Sequence[str], references: Sequence[str]) -> Tuple[List[Optional[float]], Dict[str, Any]]:
    if os.environ.get("DISABLE_BERTSCORE", "").lower() in {"1", "true", "yes"}:
        return [None for _ in predictions], {"bertscore_available": False, "bertscore_disabled": True}
    if not predictions:
        return [], {"bertscore_available": False, "bertscore_error": "no_predictions"}
    try:
        from bert_score import score as bert_score_score
    except Exception as exc:
        return [None for _ in predictions], {
            "bertscore_available": False,
            "bertscore_error": f"bert_score import failed: {type(exc).__name__}: {exc}",
        }
    kwargs: Dict[str, Any] = {"lang": os.environ.get("BERTSCORE_LANG", "en"), "verbose": False}
    model_type = os.environ.get("BERTSCORE_MODEL_TYPE")
    if model_type:
        kwargs["model_type"] = model_type
    device = os.environ.get("BERTSCORE_DEVICE")
    if device:
        kwargs["device"] = device
    batch_size = os.environ.get("BERTSCORE_BATCH_SIZE")
    if batch_size:
        kwargs["batch_size"] = int(batch_size)
    try:
        _, _, f1_scores = bert_score_score(list(predictions), list(references), **kwargs)
    except Exception as exc:
        return [None for _ in predictions], {
            "bertscore_available": False,
            "bertscore_error": f"bert_score compute failed: {type(exc).__name__}: {exc}",
        }
    return [float(value) for value in f1_scores.tolist()], {
        "bertscore_available": True,
        "bertscore_lang": kwargs["lang"],
        "bertscore_model_type": model_type or "bert_score_default",
    }


def safe_generation_metrics(gold: str, pred: str) -> Dict[str, Any]:
    try:
        return generation_overlap_metrics(gold, pred)
    except Exception as exc:
        return {
            "rouge_l_f1": None,
            "meteor": None,
            "bleu_1": None,
            "bleu_2": None,
            "bleu_3": None,
            "metric_error": f"{type(exc).__name__}: {exc}",
        }


def safe_rouge_1_2_l(gold: str, pred: str) -> Dict[str, Any]:
    try:
        from rouge_score import rouge_scorer
    except Exception as exc:
        return {
            "rouge1": None,
            "rouge2": None,
            "rougeL": None,
            "rouge_error": f"rouge_score import failed: {type(exc).__name__}: {exc}",
        }
    try:
        scores = rouge_scorer.RougeScorer(["rouge1", "rouge2", "rougeL"], use_stemmer=True).score(str(gold), str(pred))
    except Exception as exc:
        return {
            "rouge1": None,
            "rouge2": None,
            "rougeL": None,
            "rouge_error": f"rouge_score compute failed: {type(exc).__name__}: {exc}",
        }
    return {
        "rouge1": float(scores["rouge1"].fmeasure),
        "rouge2": float(scores["rouge2"].fmeasure),
        "rougeL": float(scores["rougeL"].fmeasure),
    }


class ClimateFinanceBenchEvaluator(BaseEvaluator):
    evaluator_name = "ClimateFinanceBenchEvaluator"
    dataset_key = "climate_finance_bench"

    def __init__(self, original_eval_code: Optional[Dict[str, Any]] = None) -> None:
        super().__init__(original_eval_code=original_eval_code)
        for item in self.original_eval_code.get("files", []):
            path = item.get("path", "")
            if path.endswith("sustainability-reports-rag-pipeline.ipynb"):
                self.status.original_code_path = path
                self.status.notes = (
                    "Climate Finance Bench RAG notebook discovered; generation prompt mirrors the notebook QA template, "
                    "and fallback answer-similarity metrics are used for JSONL adapter scoring."
                )
                break
        if self.status.original_code_path is None:
            for item in self.original_eval_code.get("files", []):
                if Path(item.get("path", "")).name.lower() == "readme.md":
                    self.status.original_code_path = item["path"]
                    self.status.notes = "Climate Finance Bench README discovered; no importable scorer function found."
                    break

    def evaluate(self, records: Sequence[Dict[str, Any]], predictions: Sequence[Dict[str, Any]]) -> Dict[str, Any]:
        gold_answers = [extract_assistant_answer_text(record) for record in records]
        pred_answers = [extract_prediction_answer_text(prediction.get("raw_prediction", "")) for prediction in predictions]
        bertscore_values, bertscore_info = compute_optional_bertscore_f1(pred_answers, gold_answers)
        rows = []
        numeric_available = 0
        numeric_correct = 0
        for record, gold, pred, bertscore_f1 in zip(records, gold_answers, pred_answers, bertscore_values):
            gold_numeric = numeric_value(gold)
            pred_numeric = numeric_value(pred)
            numeric_match = None
            if gold_numeric is not None:
                numeric_available += 1
                numeric_match = pred_numeric is not None and abs(gold_numeric - pred_numeric) <= max(1e-6, abs(gold_numeric) * 0.01)
                numeric_correct += int(bool(numeric_match))
            overlap = safe_generation_metrics(gold, pred)
            rows.append(
                {
                    "record_id": record.get("record_id"),
                    "em": float(normalize_answer_text(gold) == normalize_answer_text(pred)),
                    "token_f1": token_f1(gold, pred),
                    "rouge_l": overlap.get("rouge_l_f1"),
                    "bertscore_f1": bertscore_f1,
                    "numeric_match": numeric_match,
                }
            )
        return {
            "example_count": len(records),
            "em": average_metric(rows, "em") or 0.0,
            "token_f1": average_metric(rows, "token_f1") or 0.0,
            "rouge_l": average_metric(rows, "rouge_l"),
            "bertscore_f1": average_metric(rows, "bertscore_f1"),
            "numeric_accuracy_if_available": (numeric_correct / numeric_available) if numeric_available else None,
            "numeric_eval_count": numeric_available,
            **bertscore_info,
        }


def fallback_validate_prediction(pred_str: str) -> str:
    if pred_str is None:
        return "INVALID"

    s = str(pred_str).strip()
    if not s:
        return "INVALID"

    if s == "Z":
        return s
    if all(c in "ABCD" for c in s):
        return "".join(sorted(set(s)))

    s = " ".join(re.sub("[^A-Za-z]", " ", str(pred_str)).split()).strip()
    if not s:
        return "INVALID"

    s = " ".join(word.strip() for word in s.split() if not any(ch.islower() for ch in word)).strip()
    if not s:
        return "INVALID"

    s = " ".join(word for word in s.split() if all(ch in "ABCDZ" for ch in word)).strip()
    if not s:
        return "INVALID"

    if s == "Z":
        return "Z"
    if "Z" in s:
        return "INVALID"

    result = "".join(sorted(set(s))).strip()
    if not result:
        return "INVALID"
    return result


def load_esgenius_validate_prediction_from_source(path: Path) -> Optional[Any]:
    try:
        source = path.read_text(encoding="utf-8")
        tree = ast.parse(source, filename=str(path))
        function_node = None
        for node in tree.body:
            if isinstance(node, ast.FunctionDef) and node.name == "validate_prediction":
                function_node = node
                break
        if function_node is None:
            return None
        module = ast.Module(body=[function_node], type_ignores=[])
        ast.fix_missing_locations(module)
        namespace: Dict[str, Any] = {"re": re, "INVALID_ANSWER_MARKER": "INVALID"}
        exec(compile(module, filename=str(path), mode="exec"), namespace)
        validate_fn = namespace.get("validate_prediction")
        if callable(validate_fn):
            setattr(validate_fn, "_esgpt_original_load_method", "source_extracted")
            return validate_fn
    except Exception as exc:
        return None
    return None


def import_esgenius_validate_prediction(path: str) -> Optional[Any]:
    if not path:
        return None
    module_path = Path(path)
    if module_path.name != "evaluation_utils.py":
        candidate = module_path.parent / "evaluation_utils.py"
        if candidate.exists():
            module_path = candidate
    try:
        spec = importlib.util.spec_from_file_location("esgenius_original_evaluation_utils", module_path)
        if spec is not None and spec.loader is not None:
            module = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(module)
            validate_fn = getattr(module, "validate_prediction", None)
            if callable(validate_fn):
                setattr(validate_fn, "_esgpt_original_load_method", "module_import")
                return validate_fn
    except Exception:
        pass
    return load_esgenius_validate_prediction_from_source(module_path)


