def generate_benchmark_predictions(
    model: Any,
    tokenizer: Any,
    records: Sequence[Dict[str, Any]],
    *,
    batch_size: int,
    max_input_length: int,
    max_new_tokens: int,
    max_new_tokens_generation: int,
    chat_template_enable_thinking: Optional[bool],
    do_sample: bool = False,
    temperature: Optional[float] = None,
    top_p: Optional[float] = None,
    top_k: Optional[int] = None,
    seed: Optional[int] = None,
) -> List[Dict[str, Any]]:
    from .evaluation import generate_from_prompt_texts

    grouped_indices: Dict[str, List[int]] = defaultdict(list)
    prompt_texts_by_index: Dict[int, str] = {}
    prompt_tokens_by_index: Dict[int, int] = {}
    for index, record in enumerate(records):
        evaluator_name = choose_evaluator_name(record)
        grouped_indices[evaluator_name].append(index)
        if evaluator_name == "ESGeniusEvaluator" or is_esgenius_record(record):
            prompt_text = build_esgenius_original_prompt(record)
        elif evaluator_name == "ClimateFinanceBenchEvaluator" or is_climate_finance_bench_record(record):
            prompt_text = build_climate_finance_bench_original_prompt(record)
        else:
            prompt_messages = prompt_messages_for_record(record)
            prompt_text = render_chat_messages(
                tokenizer,
                prompt_messages,
                add_generation_prompt=True,
                enable_thinking=chat_template_enable_thinking,
            )
        prompt_texts_by_index[index] = prompt_text
        prompt_tokens_by_index[index] = min(
            len(tokenizer(prompt_text, add_special_tokens=False).input_ids),
            max_input_length,
        )

    raw_by_index: Dict[int, str] = {}
    for evaluator_name, indices in grouped_indices.items():
        if evaluator_name == "ChatReportEvaluator":
            evaluator_max_new_tokens = max_new_tokens_generation
        elif evaluator_name == "ESGeniusEvaluator":
            evaluator_max_new_tokens = min(max_new_tokens, 10)
        else:
            evaluator_max_new_tokens = max_new_tokens
        prompt_texts = [prompt_texts_by_index[index] for index in indices]
        print(
            f"Generating predictions with {evaluator_name}: examples={len(indices)}, "
            f"max_new_tokens={evaluator_max_new_tokens}, do_sample={do_sample}",
            flush=True,
        )
        generated = generate_from_prompt_texts(
            model=model,
            tokenizer=tokenizer,
            prompt_texts=prompt_texts,
            batch_size=batch_size,
            max_input_length=max_input_length,
            max_new_tokens=evaluator_max_new_tokens,
            do_sample=do_sample,
            temperature=temperature,
            top_p=top_p,
            top_k=top_k,
            seed=seed,
            progress_desc=evaluator_name,
        )
        for index, text in zip(indices, generated):
            raw_by_index[index] = text

    predictions: List[Dict[str, Any]] = []
    for index, record in enumerate(records):
        predictions.append(
            {
                "id": record.get("id"),
                "record_id": record.get("record_id"),
                "sample_id": record.get("sample_id"),
                "category": record.get("category"),
                "task_name": record.get("task_name"),
                "source_folder": record.get("source_folder"),
                "source_dataset": record.get("source_dataset"),
                "gold_label_or_type": record.get("detected_label"),
                "evaluator_name": choose_evaluator_name(record),
                "prompt_text": prompt_texts_by_index[index],
                "raw_prediction": raw_by_index.get(index, ""),
                "prompt_tokens": prompt_tokens_by_index[index],
                "do_sample": do_sample,
                "temperature": temperature,
                "top_p": top_p,
                "top_k": top_k,
                "seed": seed,
            }
        )
    return predictions


class OpenAICompatibleApiClient:
    def __init__(
        self,
        *,
        api_key: str,
        base_url: str,
        model: str,
        timeout: float,
        max_retries: int,
        retry_sleep: float,
        thinking_type: Optional[str],
        reasoning_effort: Optional[str],
        temperature: Optional[float],
        provider: str = "deepseek",
    ) -> None:
        self.api_key = api_key
        self.base_url = base_url.rstrip("/")
        self.model = model
        self.timeout = timeout
        self.max_retries = max_retries
        self.retry_sleep = retry_sleep
        self.thinking_type = thinking_type
        self.reasoning_effort = reasoning_effort
        self.temperature = temperature
        self.provider = provider

    def create_chat_completion(self, messages: Sequence[Dict[str, str]], *, max_tokens: int) -> Dict[str, Any]:
        payload: Dict[str, Any] = {
            "model": self.model,
            "messages": list(messages),
            "stream": False,
        }
        if self.provider == "openai":
            payload["max_completion_tokens"] = max_tokens
            if self.reasoning_effort:
                payload["reasoning_effort"] = self.reasoning_effort
        else:
            payload["max_tokens"] = max_tokens
            if self.thinking_type:
                payload["thinking"] = {"type": self.thinking_type}
                if self.thinking_type == "enabled" and self.reasoning_effort:
                    payload["reasoning_effort"] = self.reasoning_effort
        if self.temperature is not None and self.thinking_type != "enabled":
            payload["temperature"] = self.temperature

        body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        request = urllib.request.Request(
            f"{self.base_url}/chat/completions",
            data=body,
            headers={
                "Authorization": f"Bearer {self.api_key}",
                "Content-Type": "application/json",
            },
            method="POST",
        )

        last_error: Optional[Exception] = None
        for attempt in range(self.max_retries + 1):
            try:
                with urllib.request.urlopen(request, timeout=self.timeout) as response:
                    return json.loads(response.read().decode("utf-8"))
            except urllib.error.HTTPError as exc:
                response_body = exc.read().decode("utf-8", errors="replace")
                last_error = RuntimeError(f"HTTP {exc.code}: {response_body[:1000]}")
                if exc.code not in {408, 409, 429, 500, 502, 503, 504} or attempt >= self.max_retries:
                    break
            except Exception as exc:
                last_error = exc
                if attempt >= self.max_retries:
                    break
            time.sleep(self.retry_sleep * (2**attempt))
        raise RuntimeError(f"API request failed after {self.max_retries + 1} attempts: {last_error}")


def api_messages_for_record(record: Dict[str, Any]) -> List[Dict[str, str]]:
    evaluator_name = choose_evaluator_name(record)
    if evaluator_name == "ESGeniusEvaluator" or is_esgenius_record(record):
        return [{"role": "user", "content": build_esgenius_original_prompt(record)}]
    if evaluator_name == "ClimateFinanceBenchEvaluator" or is_climate_finance_bench_record(record):
        return [{"role": "user", "content": build_climate_finance_bench_original_prompt(record)}]
    return prompt_messages_for_record(record)


def approximate_prompt_tokens_from_messages(messages: Sequence[Dict[str, str]]) -> int:
    text = "\n".join(str(message.get("content", "")) for message in messages)
    return max(1, len(text) // 4)


def extract_api_message_content(response: Dict[str, Any]) -> Tuple[str, Optional[str], Dict[str, Any]]:
    choices = response.get("choices") or []
    if not choices:
        return "", None, {}
    choice = choices[0]
    message = choice.get("message") or {}
    content = message.get("content")
    if content is None:
        content = ""
    return str(content), choice.get("finish_reason"), response.get("usage") or {}


def generate_benchmark_api_predictions(
    *,
    client: OpenAICompatibleApiClient,
    records: Sequence[Dict[str, Any]],
    max_new_tokens: int,
    max_new_tokens_generation: int,
    progress_every: int,
) -> List[Dict[str, Any]]:
    predictions: List[Dict[str, Any]] = []
    total = len(records)
    for index, record in enumerate(records):
        evaluator_name = choose_evaluator_name(record)
        if evaluator_name == "ChatReportEvaluator":
            max_tokens = max_new_tokens_generation
        elif evaluator_name == "ESGeniusEvaluator":
            max_tokens = min(max_new_tokens, 10)
        else:
            max_tokens = max_new_tokens
        messages = api_messages_for_record(record)
        response = client.create_chat_completion(messages, max_tokens=max_tokens)
        raw_prediction, finish_reason, usage = extract_api_message_content(response)
        predictions.append(
            {
                "id": record.get("id"),
                "record_id": record.get("record_id"),
                "sample_id": record.get("sample_id"),
                "category": record.get("category"),
                "task_name": record.get("task_name"),
                "source_folder": record.get("source_folder"),
                "source_dataset": record.get("source_dataset"),
                "gold_label_or_type": record.get("detected_label"),
                "evaluator_name": evaluator_name,
                "prompt_text": "\n".join(str(message.get("content", "")) for message in messages),
                "raw_prediction": raw_prediction,
                "prompt_tokens": approximate_prompt_tokens_from_messages(messages),
                "api_model": client.model,
                "api_provider": client.provider,
                "api_finish_reason": finish_reason,
                "api_usage": usage,
            }
        )
        if progress_every > 0 and ((index + 1) % progress_every == 0 or index + 1 == total):
            print(f"{client.provider} API predictions ({client.model}): {index + 1}/{total}", flush=True)
    return predictions


