def discover_original_eval_code(dataset_root: Path, output_dir: Optional[Path] = None) -> Dict[str, Any]:
    dataset_root = dataset_root.resolve()
    dataset_markers = {
        "climate_finance_bench": ["climate_finance_bench", "climate finance bench", "climate_finance"],
        "esgenius": ["esgenius", "esg_qa"],
        "chatreport": ["chatreport"],
    }
    inventory: Dict[str, Any] = {
        key: {
            "category": policy["category"],
            "preferred": policy["preferred"],
            "fallback_metrics": policy["fallback_metrics"],
            "files": [],
            "importable": False,
            "import_test_error": None,
        }
        for key, policy in DATASET_SPECIFIC_EVALUATORS.items()
    }
    search_roots = []
    for rel in DISCOVERY_DIRS:
        candidate = dataset_root / rel
        if candidate.exists():
            search_roots.append(candidate)
    if dataset_root.exists():
        search_roots.append(dataset_root)

    seen_paths: set[Path] = set()
    for root in search_roots:
        for path in root.rglob("*"):
            if not path.is_file() or path in seen_paths:
                continue
            seen_paths.add(path)
            name = path.name
            if name not in DISCOVERY_FILENAMES and not name.startswith("eval_"):
                continue
            lowered = str(path).lower()
            for dataset_key, markers in dataset_markers.items():
                if any(marker in lowered for marker in markers):
                    inventory[dataset_key]["files"].append(
                        {
                            "path": str(path),
                            "name": name,
                            "suffix": path.suffix,
                            "size_bytes": path.stat().st_size,
                        }
                    )

    for dataset_key, info in inventory.items():
        if dataset_key == "esgenius":
            original_path = None
            for item in info["files"]:
                if item["path"].endswith("evaluation_utils.py"):
                    original_path = item["path"]
                    break
            validate_fn = import_esgenius_validate_prediction(original_path) if original_path else None
            info["importable"] = validate_fn is not None
            if validate_fn is None and original_path:
                info["import_test_error"] = "Could not import validate_prediction from evaluation_utils.py."
        else:
            info["importable"] = False
            info["import_test_error"] = "No importable automatic scoring function was identified."

    if output_dir is not None:
        write_json(output_dir / "original_eval_code_inventory.json", inventory)
    return inventory


