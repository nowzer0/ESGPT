def evaluate_predictions_by_adapter(
    records: Sequence[Dict[str, Any]],
    predictions: Sequence[Dict[str, Any]],
    evaluators: Dict[str, BaseEvaluator],
) -> Tuple[Dict[str, Any], Dict[str, Dict[str, Any]]]:
    grouped: Dict[str, List[Tuple[Dict[str, Any], Dict[str, Any]]]] = defaultdict(list)
    for record, prediction in zip(records, predictions):
        grouped[prediction["evaluator_name"]].append((record, prediction))

    evaluator_results: Dict[str, Dict[str, Any]] = {}
    dataset_specific_results: Dict[str, Dict[str, Any]] = {}
    for evaluator_name, pairs in sorted(grouped.items()):
        evaluator = evaluators[evaluator_name]
        group_records = [pair[0] for pair in pairs]
        group_predictions = [pair[1] for pair in pairs]
        metrics = evaluator.evaluate(group_records, group_predictions)
        metrics["evaluator_name"] = evaluator_name
        metrics["used_original_eval_code"] = evaluator.status.used_original_code
        metrics["fallback_metric_used"] = evaluator.status.fallback_used
        metrics["original_code_path"] = evaluator.status.original_code_path
        evaluator_results[evaluator_name] = metrics
        if evaluator.dataset_key in DATASET_SPECIFIC_EVALUATORS:
            dataset_specific_results[evaluator.dataset_key] = metrics
    return evaluator_results, dataset_specific_results


