def compact_scalar_metrics(metrics: Dict[str, Any]) -> Dict[str, Any]:
    compact: Dict[str, Any] = {}
    for key, value in metrics.items():
        if isinstance(value, (str, int, float, bool)) or value is None:
            compact[key] = value
    return compact


def evaluate_metric_group(
    *,
    group_type: str,
    group_keys: Dict[str, Any],
    pairs: Sequence[Tuple[Dict[str, Any], Dict[str, Any]]],
    evaluators: Dict[str, BaseEvaluator],
) -> Dict[str, Any]:
    evaluator_name = pairs[0][1]["evaluator_name"]
    evaluator = evaluators[evaluator_name]
    group_records = [pair[0] for pair in pairs]
    group_predictions = [pair[1] for pair in pairs]
    metrics = compact_scalar_metrics(evaluator.evaluate(group_records, group_predictions))
    return {
        "group_type": group_type,
        "category": group_keys.get("category", ""),
        "task_name": group_keys.get("task_name", ""),
        "source_folder": group_keys.get("source_folder", ""),
        "source_dataset": group_keys.get("source_dataset", ""),
        "evaluator_name": evaluator_name,
        **metrics,
        "used_original_eval_code": evaluator.status.used_original_code,
        "fallback_metric_used": evaluator.status.fallback_used,
        "original_code_path": evaluator.status.original_code_path,
    }


def write_metric_breakdown_reports(
    *,
    records: Sequence[Dict[str, Any]],
    predictions: Sequence[Dict[str, Any]],
    evaluators: Dict[str, BaseEvaluator],
    output_dir: Path,
) -> Dict[str, Any]:
    by_category: Dict[Tuple[str, str], List[Tuple[Dict[str, Any], Dict[str, Any]]]] = defaultdict(list)
    by_task: Dict[Tuple[str, str, str, str], List[Tuple[Dict[str, Any], Dict[str, Any]]]] = defaultdict(list)

    for record, prediction in zip(records, predictions):
        evaluator_name = prediction["evaluator_name"]
        category = str(record.get("category") or prediction.get("category") or "")
        task_name = str(record.get("task_name") or prediction.get("task_name") or "")
        source_folder = str(record.get("source_folder") or prediction.get("source_folder") or task_name)
        source_dataset = str(record.get("source_dataset") or prediction.get("source_dataset") or source_folder.split("__", 1)[0])
        pair = (record, prediction)
        by_category[(category, evaluator_name)].append(pair)
        by_task[(category, task_name, source_folder, evaluator_name)].append(pair)

    category_rows = [
        evaluate_metric_group(
            group_type="category",
            group_keys={"category": category},
            pairs=pairs,
            evaluators=evaluators,
        )
        for (category, _), pairs in sorted(by_category.items())
    ]
    task_rows = [
        evaluate_metric_group(
            group_type="task",
            group_keys={
                "category": category,
                "task_name": task_name,
                "source_folder": source_folder,
                "source_dataset": source_folder.split("__", 1)[0],
            },
            pairs=pairs,
            evaluators=evaluators,
        )
        for (category, task_name, source_folder, _), pairs in sorted(by_task.items())
    ]

    write_json(output_dir / "metrics_by_category.json", {"rows": category_rows})
    write_json(output_dir / "metrics_by_task.json", {"rows": task_rows})
    write_csv(output_dir / "metrics_by_category.csv", category_rows, BREAKDOWN_METRIC_FIELDS)
    write_csv(output_dir / "metrics_by_task.csv", task_rows, BREAKDOWN_METRIC_FIELDS)

    task_macro_rows = build_category_task_macro_summary(task_rows)
    write_json(output_dir / "metrics_by_category_task_macro.json", {"rows": task_macro_rows})
    write_csv(
        output_dir / "metrics_by_category_task_macro.csv",
        task_macro_rows,
        [
            "category",
            "task_count",
            "example_count",
            "primary_score_mean",
            "classification_macro_f1_mean",
            "classification_accuracy_mean",
            "qa_token_f1_mean",
            "reasoning_accuracy_mean",
            "multilabel_micro_f1_mean",
            "notes",
        ],
    )
    return {"metrics_by_category": category_rows, "metrics_by_task": task_rows, "metrics_by_category_task_macro": task_macro_rows}


def task_primary_score(row: Dict[str, Any]) -> Optional[float]:
    evaluator_name = row.get("evaluator_name")
    if evaluator_name == "ClassificationEvaluator":
        value = row.get("macro_f1")
    elif evaluator_name == "MultiLabelClassificationEvaluator":
        value = row.get("micro_f1")
    elif evaluator_name == "ClimateFinanceBenchEvaluator":
        value = row.get("token_f1")
    elif evaluator_name == "ESGeniusEvaluator":
        value = row.get("accuracy")
    else:
        value = row.get("accuracy")
    return float(value) if isinstance(value, (int, float)) else None


def mean_from_rows(rows: Sequence[Dict[str, Any]], key: str) -> Optional[float]:
    return safe_float_mean([row.get(key) for row in rows])


def build_category_task_macro_summary(task_rows: Sequence[Dict[str, Any]]) -> List[Dict[str, Any]]:
    grouped: Dict[str, List[Dict[str, Any]]] = defaultdict(list)
    for row in task_rows:
        grouped[str(row.get("category", ""))].append(row)
    output = []
    for category, rows in sorted(grouped.items()):
        classification_rows = [row for row in rows if row.get("evaluator_name") == "ClassificationEvaluator"]
        qa_rows = [row for row in rows if row.get("evaluator_name") == "ClimateFinanceBenchEvaluator"]
        reasoning_rows = [row for row in rows if row.get("evaluator_name") == "ESGeniusEvaluator"]
        multilabel_rows = [row for row in rows if row.get("evaluator_name") == "MultiLabelClassificationEvaluator"]
        output.append(
            {
                "category": category,
                "task_count": len(rows),
                "example_count": sum(int(row.get("example_count") or 0) for row in rows),
                "primary_score_mean": safe_float_mean([task_primary_score(row) for row in rows]),
                "classification_macro_f1_mean": mean_from_rows(classification_rows, "macro_f1"),
                "classification_accuracy_mean": mean_from_rows(classification_rows, "accuracy"),
                "qa_token_f1_mean": mean_from_rows(qa_rows, "token_f1"),
                "reasoning_accuracy_mean": mean_from_rows(reasoning_rows, "accuracy"),
                "multilabel_micro_f1_mean": mean_from_rows(multilabel_rows, "micro_f1"),
                "notes": "Mean over task-level primary metrics; preferred over pooled category macro-F1 when label spaces differ.",
            }
        )
    return output


def evaluator_usage_summary(evaluators: Dict[str, BaseEvaluator]) -> Dict[str, Dict[str, Any]]:
    summary: Dict[str, Dict[str, Any]] = {}
    for evaluator in evaluators.values():
        if evaluator.dataset_key not in DATASET_SPECIFIC_EVALUATORS:
            continue
        summary[evaluator.dataset_key] = {
            "evaluator": evaluator.evaluator_name,
            "used_original_code": evaluator.status.used_original_code,
            "fallback_used": evaluator.status.fallback_used,
            "original_code_path": evaluator.status.original_code_path,
            "notes": evaluator.status.notes,
        }
    return summary


def build_eval_summary_md(summary: Dict[str, Any]) -> str:
    lines = [
        "# ESG Benchmark Evaluation Summary",
        "",
        f"- Benchmark file: `{summary['benchmark_file']}`",
        f"- Examples: `{summary['example_count']}`",
        f"- Started: `{summary['started_at_utc']}`",
        f"- Ended: `{summary['ended_at_utc']}`",
        "",
        "## Evaluator Usage",
    ]
    for dataset_key, usage in summary.get("evaluator_usage_summary", {}).items():
        lines.append(
            f"- `{dataset_key}`: `{usage['evaluator']}`, "
            f"used_original_code=`{usage['used_original_code']}`, fallback_used=`{usage['fallback_used']}`"
        )
    lines.extend(
        [
            "",
            "## Metrics",
        ]
    )
    for evaluator_name, metrics in summary.get("evaluator_results", {}).items():
        lines.append(f"### {evaluator_name}")
        for key, value in metrics.items():
            if isinstance(value, (int, float, str)) or value is None:
                lines.append(f"- `{key}`: `{value}`")
    lines.extend(
        [
            "",
            "## Important Warnings",
            f"- {CHATREPORT_WARNING}",
            f"- {ORIGINAL_EVALUATOR_WARNING}",
        ]
    )
    return "\n".join(lines) + "\n"


